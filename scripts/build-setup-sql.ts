/**
 * Builds supabase/setup.sql: every migration in order, the starter questions, and a final step
 * that sets a random password for the pricele_app role and shows it once. This lets an operator
 * set up a fresh Supabase project with a single paste into the SQL Editor (no CLI needed).
 *
 *   npm run db:setup-sql
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(__dirname, "..");
const dir = join(root, "supabase", "migrations");
const migrations = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  `-- PRICELE ONE-PASTE SETUP for a NEW, EMPTY Supabase project.
-- Generated by \`npm run db:setup-sql\` from supabase/migrations and supabase/seed.sql. Do not edit by hand.
-- Paste this whole file into Supabase > SQL Editor > New query, then click Run.
-- The last result shows two values (app password and cron secret). Copy both somewhere safe.
-- Run it once. To update an existing project later, run only the new migration files.
`,
  ...migrations.map((f) => `\n-- ==== ${f} ====\n${readFileSync(join(dir, f), "utf8")}`),
  `\n-- ==== starter questions (supabase/seed.sql) ====\n${readFileSync(join(root, "supabase", "seed.sql"), "utf8")}`,
  `
-- ==== app password and cron secret ====
create or replace function pg_temp.pricele_finish_setup()
returns table (app_password text, cron_secret text)
language plpgsql
as $$
declare
  v_pw text := encode(extensions.gen_random_bytes(24), 'hex');
begin
  execute format('alter role pricele_app with login password %L', v_pw);
  return query select v_pw, encode(extensions.gen_random_bytes(24), 'hex');
end;
$$;

select * from pg_temp.pricele_finish_setup();
`,
];

writeFileSync(join(root, "supabase", "setup.sql"), parts.join(""));
console.log(`Wrote supabase/setup.sql from ${migrations.length} migrations + starter questions.`);
