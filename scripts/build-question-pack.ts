/**
 * Turns a question pack (supabase/question-packs/<name>.json) into one SQL file that can be pasted
 * into the Supabase SQL Editor. Every question arrives as an UNVERIFIED DRAFT with its answer and
 * source; re-running is safe (rows are keyed by slug).
 *
 *   npx tsx scripts/build-question-pack.ts pack-02
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Q = {
  slug: string; difficulty: "easy" | "medium" | "hard"; category: string; prompt: string; context: string;
  image: string; imageAlt: string; amount: string; definition: string; referenceDate: string; explanation: string;
  source: { title: string; publisher: string; url: string; excerpt: string }; notes?: string;
};

const name = process.argv[2];
if (!name) throw new Error("usage: build-question-pack <pack-name>");
const root = join(import.meta.dirname, "..");
const pack = JSON.parse(readFileSync(join(root, "supabase", "question-packs", `${name}.json`), "utf8")) as {
  researchedOn: string; questions: Q[]; days?: string[][];
};

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const problems: string[] = [];
const slugs = new Set<string>();
for (const q of pack.questions) {
  if (slugs.has(q.slug)) problems.push(`duplicate slug ${q.slug}`);
  slugs.add(q.slug);
  if (!/^\d+(\.\d{1,2})?$/.test(q.amount) || Number(q.amount) <= 0) problems.push(`${q.slug}: bad amount`);
  if (!/^\/items\/[a-z0-9-]+\.svg$/.test(q.image) || !existsSync(join(root, "public", q.image))) problems.push(`${q.slug}: missing picture ${q.image}`);
  if (!/^https:\/\//.test(q.source.url)) problems.push(`${q.slug}: source must be https`);
  if (q.explanation.length < 20) problems.push(`${q.slug}: explanation too short`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(q.referenceDate)) problems.push(`${q.slug}: bad reference date`);
}
if (problems.length) throw new Error(problems.join("\n"));

const rows = pack.questions
  .map((q) =>
    `      (${[q.slug, q.difficulty, q.category, q.prompt, q.context, q.image, q.imageAlt].map(lit).join(", ")}, ${q.amount}, ` +
    `${[q.definition, q.referenceDate, q.explanation, q.source.title, q.source.publisher, q.source.url, q.source.excerpt, q.notes ?? ""].map(lit).join(", ")})`,
  )
  .join(",\n");

const counts = ["easy", "medium", "hard"].map((d) => `${pack.questions.filter((q) => q.difficulty === d).length} ${d}`).join(", ");
const sql = `-- QUESTION PACK ${name} — ${pack.questions.length} real items (${counts}), researched on ${pack.researchedOn}.
-- Generated by \`npx tsx scripts/build-question-pack.ts ${name}\` from supabase/question-packs/${name}.json.
-- HOW TO USE: Supabase → SQL Editor → New query → paste this whole file → Run. Run it once
-- (running again is harmless: existing questions are skipped). Then open each question in
-- /admin/questions, check its source, mark it verified and approve it.
-- Everything is inserted as an UNVERIFIED DRAFT. Pictures ship with the site under /items/.

do $$
declare
  r record;
  v_qid uuid;
  v_added int := 0;
begin
  for r in
    select * from (values
${rows}
    ) as t(slug, difficulty, cat, prompt, context, image, image_alt, amount, definition, ref_date, explanation,
           src_title, src_publisher, src_url, src_excerpt, src_notes)
  loop
    insert into public.questions (slug, prompt, context, difficulty, category_id, image_url, image_alt, image_credit, status, is_sample)
    values (r.slug, r.prompt, r.context, r.difficulty, (select id from public.categories where slug = r.cat),
            r.image, r.image_alt, 'Illustration: Pricele', 'draft', false)
    on conflict (slug) do nothing
    returning id into v_qid;

    if v_qid is not null then
      v_added := v_added + 1;
      insert into public.question_answers (question_id, answer_amount, answer_definition, reference_date, explanation)
      values (v_qid, r.amount, r.definition, r.ref_date::date, r.explanation);
      insert into public.question_sources (question_id, title, publisher, source_url, supporting_excerpt, verification_notes)
      values (v_qid, r.src_title, r.src_publisher, r.src_url, r.src_excerpt,
              concat_ws(' ', 'Researched ${pack.researchedOn}; re-check before verifying.', nullif(r.src_notes, '')));
    end if;
  end loop;
  raise notice 'Question pack ${name}: % new draft questions added', v_added;
end
$$;

select count(*) filter (where slug like any (array[${[...slugs].map(lit).join(", ")}])) as questions_in_pack
  from public.questions;
`;
writeFileSync(join(root, "supabase", "question-packs", `${name}.sql`), sql);
console.log(`Wrote supabase/question-packs/${name}.sql (${pack.questions.length} questions: ${counts})`);
